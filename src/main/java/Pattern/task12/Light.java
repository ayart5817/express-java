package Pattern.task12;

class Light {
    public void On() {
        System.out.println("Свет включён");
    }

    public void Off() {
        System.out.println("Свет выключен");
    }
}

class AirConditioned {
    public void conditionedOn() {
        System.out.println("Кондиционер включён");
    }

    public void conditionedOff() {
        System.out.println("Кондиционер выключен");
    }
}

class SecuritySystem {
    public void arm() {
        System.out.println("Система охраны включена");
    }

    public void disarm() {
        System.out.println("Система охраны выключена");
    }
}

