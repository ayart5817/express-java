package Pattern.task11;

class DoorOpener {
    public void open() {
        System.out.println("Door open");
    }
}

class DoorCloser {
    public void close() {
        System.out.println("Door close");
    }
}

class DoorLocker {
    public void lock() {
        System.out.println("Door lock");
    }
}

class DoorUnLocker {
    public void unlock() {
        System.out.println("Door unlock");
    }
}