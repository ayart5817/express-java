package FreeTask.OOP.Notifier;

/**
 📌 Задача: Система оповещения о погоде
 В метеослужбе используются разные устройства для оповещения о погодных условиях:

 Радио — передаёт голосовое сообщение: «Ожидается дождь»
 SMS-сервер — отправляет текст: «Внимание: гроза»
 Мобильное приложение — показывает уведомление: «Снегопад, +2°C»
 Нужно создать ООП-структуру, в которой:

 Есть общий интерфейс или абстрактный класс для оповещателя.
 Каждое устройство реализует свой способ вывода сообщения.
 В главной программе создаётся список устройств, и каждое из них полиморфно выводит своё сообщение.
 🔧 Требования:
 Используйте наследование или интерфейс.
 Сообщения должны быть разными по формату (как в примере выше).
 В main — массив/список устройств, цикл по ним с вызовом единого метода (например, notify(String message)).
 Не дублируйте логику — каждый класс сам решает, как отображать сообщение.

 */
public abstract class Notifier {

    private String message;

    public abstract void sendMessage();
}
